    def _get_repo_map(self, root: Path) -> RepositoryMap:
        return RepositoryIntelligence(root).scan().repository_map

    def _get_change_impact(self, root: Path, task: str) -> ChangeImpact:
        context = RepositoryIntelligence(root).scan()
        ContextSelector(root, max_files=12).select(task, context)
        return ChangeImpactAnalyzer(root).analyze(task, context)

    def test_js_command_discovery(self):
        root = self._repository()
        repo_map = self._get_repo_map(root)
        validation_intelligence = ValidationIntelligence(root)
        commands = validation_intelligence.discover_commands(repo_map)
        command_names = {cmd.name for cmd in commands}
        self.assertIn("test", command_names)
        self.assertIn("test:unit", command_names)
        self.assertIn("test:e2e", command_names)
        self.assertIn("typecheck", command_names)
        self.assertIn("build", command_names)
        self.assertIn("lint", command_names)
        self.assertIn("format", command_names)
        self.assertIn("db:reset", command_names)
        self.assertIn("deploy", command_names)

        test_cmd = next(cmd for cmd in commands if cmd.name == "test")
        self.assertEqual(test_cmd.category, "unit_test")
        self.assertEqual(test_cmd.risk, "low")
        e2e_cmd = next(cmd for cmd in commands if cmd.name == "test:e2e")
        self.assertEqual(e2e_cmd.category, "e2e_test")
        self.assertEqual(e2e_cmd.risk, "medium")
        db_reset_cmd = next(cmd for cmd in commands if cmd.name == "db:reset")
        self.assertEqual(db_reset_cmd.category, "destructive")
        self.assertEqual(db_reset_cmd.risk, "high")
        self.assertTrue(db_reset_cmd.destructive)

