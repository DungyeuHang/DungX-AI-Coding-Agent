            self.assertFalse(report.completed) # Should not be completed due to failure
            self.assertEqual(len(report.executions), 1)
            self.assertEqual(report.executions[0].command, "python fail_test.py")
            self.assertFalse(report.executions[0].succeeded)
            self.assertEqual(len(report.failures), 1)
            self.assertEqual(report.failures[0].probable_root_cause, "deterministic test failure") # From CapturingProvider.analyze_failure

